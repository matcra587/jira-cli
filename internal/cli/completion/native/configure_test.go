package native_test

import (
	"bytes"
	"testing"

	"github.com/gechr/clib/complete"

	"github.com/matcra587/jira-cli/internal/cli/completion/native"
)

func TestConfigureKeepsOtherGeneratorsIndependent(t *testing.T) {
	for name, upstream := range map[string]complete.ShellFunc{
		"bash": complete.GenerateBash, "fish": complete.GenerateFish,
		"zsh": complete.GenerateZsh, "pwsh": complete.GeneratePwsh,
		"elvish": complete.GenerateElvish, "nu": complete.GenerateNu,
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			other := complete.NewGenerator("fixture")
			want, err := upstream(other)
			if err != nil {
				t.Fatal(err)
			}
			owned := complete.NewGenerator("fixture")
			native.Configure(owned)
			var generated bytes.Buffer
			if err := owned.Print(&generated, name); err != nil {
				t.Fatal(err)
			}
			if name == "nu" && generated.String() != want {
				t.Fatal("configuration replaced the upstream Nushell client")
			}
			// Existing and later generators must both retain the library client.
			for _, generator := range []*complete.Generator{other, complete.NewGenerator("fixture")} {
				var untouched bytes.Buffer
				if err := generator.Print(&untouched, name); err != nil {
					t.Fatal(err)
				}
				if untouched.String() != want {
					t.Fatal("configuring one generator changed another generator's shell client")
				}
			}
		})
	}
}
