package main

import (
	"cmp"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/gechr/clog"

	"github.com/matcra587/jira-cli/internal/jira/spec"
)

type operation struct {
	OperationID string `json:"operationId"`
	Summary     string `json:"summary"`
	Deprecated  bool   `json:"deprecated"`
}

type document struct {
	Paths map[string]map[string]json.RawMessage `json:"paths"`
}

type entry struct {
	family, method, path string
	operation
}

func main() {
	dir := flag.String("spec-dir", "spec", "directory of pinned OpenAPI documents")
	out := flag.String("out", "api_catalog_gen.go", "generated Go output file")
	flag.Parse()
	if err := run(*dir, *out); err != nil {
		clog.Error().Parts(clog.PartMessage).Msg("gen-api-catalog: " + err.Error())
		os.Exit(1)
	}
}

func run(dir, out string) error {
	src, err := generate(dir)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}

func generate(dir string) ([]byte, error) {
	entries := []entry{}
	for _, pin := range spec.Pins() {
		// Developer-selected vendored inputs, never runtime configuration.
		raw, err := os.ReadFile(filepath.Join(dir, pin.File)) //nolint:gosec // generation reads its explicit spec directory
		if err != nil {
			return nil, err
		}
		if fmt.Sprintf("%x", sha256.Sum256(raw)) != pin.SHA256 {
			return nil, fmt.Errorf("%s does not match its pinned digest", pin.File)
		}
		family := strings.TrimSuffix(pin.File, ".json")
		selected, err := project(raw, family)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", pin.File, err)
		}
		entries = append(entries, selected...)
	}
	slices.SortFunc(entries, func(a, b entry) int {
		return cmp.Or(strings.Compare(a.path, b.path), strings.Compare(a.method, b.method), strings.Compare(a.family, b.family))
	})
	var out strings.Builder
	out.WriteString("// Code generated by gen-api-catalog from pinned OpenAPI documents. DO NOT EDIT.\n\npackage jira\n\n")
	out.WriteString("var apiCatalogSources = []APICatalogSource{\n")
	for _, pin := range spec.Pins() {
		fmt.Fprintf(&out, "{Family: %q, URL: %q, Version: %q, SHA256: %q},\n",
			strings.TrimSuffix(pin.File, ".json"), pin.URL, pin.Version, pin.SHA256)
	}
	out.WriteString("}\n\nvar apiCatalogOperations = []APIOperation{\n")
	for _, value := range entries {
		fmt.Fprintf(&out, "{Family: %q, Method: %q, Path: %q, OperationID: %q, Summary: %q, Deprecated: %t},\n",
			value.family, value.method, value.path, value.OperationID, value.Summary, value.Deprecated)
	}
	out.WriteString("}\n")
	return format.Source([]byte(out.String()))
}

func project(raw []byte, family string) ([]entry, error) {
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	entries := []entry{}
	for path, item := range doc.Paths {
		// The raw request owner admits these two REST families. Other public
		// spec paths, including app/integration routes, are not suggestions.
		if !strings.HasPrefix(path, "/rest/api/") && !strings.HasPrefix(path, "/rest/agile/") {
			continue
		}
		for _, method := range []string{"get", "head", "options", "post", "put", "patch", "delete"} {
			rawOperation, ok := item[method]
			if !ok {
				continue
			}
			var value operation
			if err := json.Unmarshal(rawOperation, &value); err != nil {
				return nil, fmt.Errorf("%s %s: %w", method, path, err)
			}
			entries = append(entries, entry{family: family, method: strings.ToUpper(method), path: path, operation: value})
		}
	}
	if len(entries) == 0 {
		return nil, fmt.Errorf("no supported REST operations")
	}
	return entries, nil
}
